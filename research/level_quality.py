"""C5VRX by Twotoz and the C5VRX contributors: build main/level_quality.h,
the measured picture quality the LEVEL AGC scores every gain row with.

Input: research/data/level_quality_grid.json (level_quality_grid.py, the
bit-exact U80P64-R1 on the physical-ADC model). Per C/N (after the filter)
and total rms radius, the quality of the four PAL/NTSC cases is averaged:

    q = 100 * lock * (SYNC_SHARE + (1 - SYNC_SHARE) * clamp(sinad / SINAD_FULL, 0, 1))

Lock first (a lost line is a lost picture), then luma SINAD; the share is the
one the formula model used. The measured rows are then made monotonic around
each C/N's best radius (non-decreasing below it, non-increasing above it), so
that seed noise cannot make a fold look better than staying under it.

    python research/level_quality.py          # write the header
    python research/level_quality.py --check  # CI: the header is current
"""
import argparse
import json
from collections import defaultdict
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
GRID = ROOT / 'research/data/level_quality_grid.json'
HEADER = ROOT / 'main/level_quality.h'
SYNC_SHARE = 0.6
SINAD_FULL = 12.0


def build():
    rows = json.loads(GRID.read_text())
    cells = defaultdict(list)
    post = defaultdict(list)
    for r in rows:
        cells[(r['cn'], r['rms'])].append(r)
        post[r['cn']].append(r['cn_post'])
    cns = sorted(post)
    rms = sorted({r['rms'] for r in rows})
    q = np.zeros((len(cns), len(rms)))
    for i, c in enumerate(cns):
        for j, m in enumerate(rms):
            v = [100 * r['lock'] * (SYNC_SHARE + (1 - SYNC_SHARE) * min(max(r['sinad'] / SINAD_FULL, 0), 1))
                 for r in cells[(c, m)]]
            q[i, j] = np.mean(v)
        best = int(np.argmax(q[i]))
        for j in range(best - 1, -1, -1):
            q[i, j] = min(q[i, j], q[i, j + 1])
        for j in range(best + 1, len(rms)):
            q[i, j] = min(q[i, j], q[i, j - 1])
    axis_cn = [int(round(10 * np.mean(post[c]))) for c in cns]
    return axis_cn, [int(round(100 * m)) for m in rms], np.rint(q).astype(int), len(rows)


def render(axis_cn, axis_rms, q, n):
    out = ['/* C5VRX-5 by Twotoz and the C5VRX contributors: measured picture quality',
           ' * (0..100) of U80P64-R1 against C/N and the total IQ radius, for the LEVEL',
           ' * AGC (agc.c). Generated by research/level_quality.py from',
           f' * research/data/level_quality_grid.json ({n} bit-exact demod cases on the',
           ' * physical-ADC model, PAL and NTSC): lock first, then luma SINAD; monotonic',
           ' * around each C/N\'s best radius. Do not edit by hand. */',
           '#pragma once',
           '#include <stdint.h>',
           '',
           f'#define LEVEL_Q_CNS {len(axis_cn)}',
           f'#define LEVEL_Q_RMS {len(axis_rms)}',
           '/* C/N after the filter (carrier over noise at the ADC), dB x10 */',
           'static const int16_t level_q_cn_x10[LEVEL_Q_CNS] = {' + ', '.join(map(str, axis_cn)) + '};',
           '/* total (carrier plus noise) rms radius, cells x100 */',
           'static const int16_t level_q_rms_x100[LEVEL_Q_RMS] = {' + ', '.join(map(str, axis_rms)) + '};',
           'static const int8_t level_q[LEVEL_Q_CNS][LEVEL_Q_RMS] = {']
    for i, row in enumerate(q):
        out.append('    {' + ', '.join(f'{v:3d}' for v in row) + '},' + f'   /* {axis_cn[i] / 10:5.1f} dB */')
    out.append('};')
    return '\n'.join(out) + '\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    text = render(*build())
    if ap.parse_args().check:
        if HEADER.read_text() != text:
            raise SystemExit('main/level_quality.h is stale: run python research/level_quality.py')
        print('level_quality.h current')
        return
    HEADER.write_text(text, newline='\n')
    print(text)


if __name__ == '__main__':
    main()

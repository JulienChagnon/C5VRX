#!/usr/bin/env python3
# C5VRX-5 by Twotoz and the C5VRX contributors: build main/dco_preset.h, the
# DC base map in the firmware, from measured boards.
#
# On each board, VTX off, run menu CALIBRATE / console F, then console C (or
# the web "Download calibration report") and save the log. Then:
#
#   python3 tools/dco_preset.py board1.log [board2.log ...] > main/dco_preset.h
#   python3 tools/dco_preset.py --check main/dco_preset.h LOG [LOG ...]
#
# Rows used: the active table (slot -1), valid OK, not a template, of the
# baseline filter (code 16, skirt 32, BW40). Several dumps of one board are
# first reduced to that board's median per gain; the preset is the median
# over boards, so repeated captures of one board count as one board.
import json
import re
import statistics
import sys

FILTER = (16, 32, 0)            # calibration_policy.h baseline: code, skirt, bw20
LINE = re.compile(r"CALDUMP_LINE n=\d+ (\{.*\})")


def dumps(path):
    """Yield (board_id, records) per CALDUMP_BEGIN..END block of a log."""
    recs, board = None, None
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            if "CALDUMP_BEGIN" in line:
                recs, board = [], None
            elif "CALDUMP_END" in line and recs is not None:
                yield board, recs
                recs = None
            elif recs is not None:
                m = LINE.search(line)
                if m:
                    r = json.loads(m.group(1))
                    if r["type"] == "device":
                        board = r["board_id"]
                    recs.append(r)


def median_int(values):
    return int(round(statistics.median(values)))


def build(paths):
    per_board = {}                  # board -> gain -> axis lists
    context = set()
    for p in paths:
        for board, recs in dumps(p):
            active = next((r for r in recs if r["type"] == "active"), None)
            live = active and (active["filter_code"], active["filter_skirt"], int(active["filter_bw20"])) == FILTER
            for r in recs:
                # A table header of code -1 predates filter recording; its own
                # rows count when the dump's live filter is the baseline (F
                # measures the current filter).
                header = (r.get("code"), r.get("skirt"), r.get("bw20"))
                if (r["type"] != "dc_row" or r["slot"] != -1 or r["valid"] != 1 or r["template"]
                        or not (header == FILTER or (header[0] == -1 and live))):
                    continue
                context.add((r["iq_scale"], r["table_version"]))
                rows = per_board.setdefault(board, {}).setdefault(r["gain"], ([], []))
                rows[0].append(r["i"])
                rows[1].append(r["q"])
    if not per_board:
        raise SystemExit("no valid own dc_row of the baseline filter found (run F, then C)")
    if len(context) != 1:
        raise SystemExit(f"dumps mix IQ scale / table versions: {sorted(context)}")
    gains = sorted({g for b in per_board.values() for g in b})
    lo, hi = gains[0], gains[-1]
    table = []
    for g in range(lo, hi + 1):
        boards = [b[g] for b in per_board.values() if g in b]
        if not boards:
            table.append((-1, -1, 0))
            continue
        table.append((median_int([median_int(b[0]) for b in boards]),
                      median_int([median_int(b[1]) for b in boards]), len(boards)))
    return per_board, context.pop(), lo, hi, table


def header(paths):
    per_board, (iq_scale, version), lo, hi, table = build(paths)
    out = [
        "/* C5VRX-5 by Twotoz and the C5VRX contributors: DC base map in the firmware.",
        f" * Generated by tools/dco_preset.py from {len(per_board)} measured board(s)",
        f" * ({', '.join(sorted(per_board))}); do not edit by hand. Median I/Q codes per",
        " * gain of the baseline filter (code 16, skirt 32, BW40), VTX off. Held for a",
        " * row without own codes of this board; F replaces it. Not calibration evidence. */",
        "#pragma once",
        "#include <stdint.h>",
        f"#define DCO_PRESET_BOARDS   {len(per_board)}u",
        f"#define DCO_PRESET_LO       {lo}u",
        f"#define DCO_PRESET_HI       {hi}u",
        f"#define DCO_PRESET_IQ_SCALE {iq_scale}u",
        f"#define DCO_PRESET_VERSION  {version}u",
        "/* {I, Q} per gain DCO_PRESET_LO..HI; -1 = no board measured the row. */",
        "static const int16_t c5vrx5_dco_preset[DCO_PRESET_HI - DCO_PRESET_LO + 1u][2] = {",
    ]
    for k, (i, q, n) in enumerate(table):
        out.append(f"    {{{i}, {q}}},   /* G{lo + k}, {n} board(s) */")
    out.append("};")
    return "\n".join(out) + "\n"


def main(argv):
    if len(argv) >= 3 and argv[1] == "--check":
        with open(argv[2], encoding="utf-8") as f:
            current = f.read()
        if current != header(argv[3:]):
            print(f"{argv[2]} is not generated from the given logs", file=sys.stderr)
            return 1
        print(f"PASS: {argv[2]} reproduces from {len(argv) - 3} log(s)")
        return 0
    if len(argv) < 2:
        print("usage: dco_preset.py LOG [LOG ...] > main/dco_preset.h", file=sys.stderr)
        return 2
    sys.stdout.write(header(argv[1:]))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))

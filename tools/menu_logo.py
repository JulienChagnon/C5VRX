#!/usr/bin/env python3
"""C5VRX-5 by Twotoz and the C5VRX contributors: boot logo generator.

Scales assets/c5vrx-white-logo.png (white on transparent) onto the menu
grid for the boot screen: logical pixels about six times taller than wide,
so the logo is LOGO_WIDTH pixels wide and only a few rows high. Each cell
holds its ink coverage as a DAC code between black (20) and white (60);
the grey edge cells keep the slanted strokes smooth. Needs Pillow; the
generated main/menu_logo.h is committed.

  python3 tools/menu_logo.py                 write main/menu_logo.h
  python3 tools/menu_logo.py --pgm out.pgm   also a UI frame for menu_preview.py
"""
import argparse
import pathlib

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "assets" / "c5vrx-white-logo.png"
OUT = ROOT / "main" / "menu_logo.h"

LOGO_WIDTH = 352            # logical pixels
PIXEL_ASPECT = 6.2          # logical pixel height / width on a 4:3 picture
BLACK, WHITE = 20, 60
UI_WIDTH, UI_ROWS, UI_BYTES = 384, 56, 1600
X_NUM, X_DEN = 208, 50


def coverage():
    img = Image.open(SRC).convert("RGBA")
    alpha = img.getchannel("A").point(lambda a: a)
    luma = img.convert("L")
    ink = Image.composite(luma, Image.new("L", img.size, 0), alpha)   # white ink on black
    ink = ink.crop(ink.getbbox())
    w, h = ink.size
    rows = max(1, round(LOGO_WIDTH * h / w / PIXEL_ASPECT))
    # Area average: supersample, then box down to the grid.
    return ink.resize((LOGO_WIDTH, rows), Image.BOX), rows


def codes(img):
    w, h = img.size
    px = img.load()
    out = []
    for y in range(h):
        row = []
        for x in range(w):
            # Thin strokes cover a cell only partly; lift them toward white
            # (a grey top on the R read as a different shade).
            c = min(1.0, 1.6 * px[x, y] / 255.0)
            c = 0.0 if c < 0.15 else 1.0 if c > 0.8 else c
            row.append(round(BLACK + (WHITE - BLACK) * c))
        # A long grey run is a thin sliver of ink (the R's joint), not an
        # edge: it read as a grey band, so it goes black. Short runs stay
        # as the anti-aliasing of the slanted edges.
        x = 0
        while x < w:
            if BLACK < row[x] < WHITE:
                e = x
                while e < w and BLACK < row[e] < WHITE:
                    e += 1
                if e - x >= 4:
                    row[x:e] = [BLACK] * (e - x)
                x = e
            else:
                x += 1
        out.append(row)
    return out


def header(rows):
    lines = [
        "/* C5VRX-5 by Twotoz and the C5VRX contributors: boot logo.",
        " * Generated by tools/menu_logo.py from assets/c5vrx-white-logo.png",
        " * (C5VRX branding, see assets/BRANDING.md). DAC codes per logical pixel. */",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define MENU_LOGO_WIDTH {len(rows[0])}u",
        f"#define MENU_LOGO_ROWS {len(rows)}u",
        "static const uint8_t s_menu_logo[MENU_LOGO_ROWS][MENU_LOGO_WIDTH] = {",
    ]
    for r in rows:
        lines.append("    {")
        for k in range(0, len(r), 24):
            lines.append("        " + ", ".join(str(v) for v in r[k:k + 24]) + ",")
        lines.append("    },")
    lines += ["};", ""]
    return "\n".join(lines)


def pgm(rows, path):
    """A UI frame with the logo centred, as test/test_menu_ui.c writes them."""
    ui = [[BLACK] * UI_BYTES for _ in range(UI_ROWS)]
    y0 = (UI_ROWS - len(rows)) // 2 - 3
    x0 = (UI_WIDTH - len(rows[0])) // 2
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            s0, s1 = (x0 + x) * X_NUM // X_DEN, (x0 + x + 1) * X_NUM // X_DEN
            for s in range(s0, s1):
                ui[y0 + y][s] = c
    data = bytes(v for row in ui for v in row)
    pathlib.Path(path).write_bytes(b"P5\n%d %d\n63\n" % (UI_BYTES, UI_ROWS) + data)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--pgm")
    a = ap.parse_args()
    img, n = coverage()
    rows = codes(img)
    OUT.write_text(header(rows), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {LOGO_WIDTH} x {n}")
    if a.pgm:
        pgm(rows, a.pgm)


if __name__ == "__main__":
    main()
